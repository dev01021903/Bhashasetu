  const OFFLINE_CATEGORIES = ["Actions", "Adjectives", "Animals", "Body Parts", "Colors", "Conversations", "Daily Life", "Family", "Food", "Greetings", "Nature", "Numbers", "Places", "Questions", "School", "Society", "Time"];

  function isMixedContentRisk() {
    return (window.location.protocol === 'https:' && baseUrl.startsWith('http://'));
  }

  /**
   * Generic fetch wrapper with clean error handling
   */
  async function requestApi(endpoint, options = {}) {
    if (isMixedContentRisk()) {
      throw new Error("Mixed content: cannot call HTTP backend from HTTPS environment.");
    }
    const url = `${baseUrl}${endpoint}`;
    const res = await fetch(url, options);
    const data = await res.json();
    if (!res.ok) {
      const errorMsg = data.message || data.error || `HTTP ${res.status}: ${res.statusText}`;
      const err = new Error(errorMsg);
      err.status = res.status;
      err.data = data;
      throw err;
    }
    return data;
  }

  function normalizeLang(lang) {
    const l = String(lang || "").trim().toLowerCase();
    if (l.includes("santhali") || l.includes("santali")) return "Santali";
    if (l.includes("nagpuri")) return "Nagpuri";
    if (l.includes("khortha")) return "Khortha";
    if (l.includes("hindi") || l.includes("hin")) return "hindi";
    if (l.includes("english") || l.includes("eng")) return "english";
    return "Santali";
  }

  function cleanSearchTerm(str) {
    return String(str || "").toLowerCase().replace(/[^\w\s\u0900-\u097F\u1C50-\u1C7F]/g, " ").replace(/\s+/g, " ").trim();
  }

  /**
   * Offline Concept Matcher
   */
  function offlineTranslate(text, fromLanguage = "english", toLanguage = "local", targetLanguage = "") {
    const rawClean = text.trim();
    const cleanTerm = cleanSearchTerm(text);
    if (!cleanTerm) {
      return { found: false, message: "Please type a word first." };
    }

    let target = normalizeLang(targetLanguage || toLanguage);
    if (target === "local") target = "Santali";

    let matched = null;

    // 1. Direct concept match
    for (const c of OFFLINE_CONCEPTS) {
      const engClean = cleanSearchTerm(c.english);
      const hinClean = cleanSearchTerm(c.hindi);
      const sanClean = cleanSearchTerm(c.Santali);
      const nagClean = cleanSearchTerm(c.Nagpuri);
      const khoClean = cleanSearchTerm(c.Khortha);

      if (
        cleanTerm === engClean ||
        cleanTerm === hinClean ||
        cleanTerm === sanClean ||
        cleanTerm === nagClean ||
        cleanTerm === khoClean ||
        engClean.split(" ").includes(cleanTerm) ||
        hinClean.split(" ").includes(cleanTerm)
      ) {
        matched = c;
        break;
      }
    }

    // 2. Substring search fallback
    if (!matched && cleanTerm.length >= 3) {
      for (const c of OFFLINE_CONCEPTS) {
        const engClean = cleanSearchTerm(c.english);
        const hinClean = cleanSearchTerm(c.hindi);
        if (engClean.includes(cleanTerm) || hinClean.includes(cleanTerm)) {
          matched = c;
          break;
        }
      }
    }

    if (!matched) {
      return {
        found: false,
        message: "We are still learning this word. Please try another one."
      };
    }

    let targetVal = matched[target] || matched.Santali || matched.Nagpuri || matched.Khortha || "";
    if (target === "english") targetVal = matched.english;
    if (target === "hindi") targetVal = matched.hindi;

    return {
      found: true,
      input: text,
      translation: targetVal,
      sourceLanguage: fromLanguage,
      targetLanguage: target,
      word: {
        id: matched.id,
        english_word: matched.english,
        hindi_word: matched.hindi,
        local_word: targetVal,
        language: target,
        category: matched.category,
        emoji: matched.emoji,
        image_url: `assets/words/${matched.english.toLowerCase().replace(/[^a-z0-9]/g, '_')}.png`,
        difficulty: matched.difficulty,
        translations: {
          english: matched.english,
          hindi: matched.hindi,
          Santali: matched.Santali,
          Nagpuri: matched.Nagpuri,
          Khortha: matched.Khortha
        }
      }
    };
  }

  /**
   * Fetch words with optional category, language, and limit filters
   */
  async function getAllWords(category = "", language = "", limit = 50) {
    try {
      const params = new URLSearchParams();
      if (category && category !== "All") params.append("category", category);
      if (language) params.append("language", language);
      if (limit) params.append("limit", limit);
      const qs = params.toString() ? `?${params.toString()}` : "";
      return await requestApi(`/api/words${qs}`);
    } catch (err) {
      // Fallback to offline dataset
      let filtered = OFFLINE_WORDS;
      if (category && category !== "All") {
        filtered = filtered.filter(w => w.category.toLowerCase() === category.toLowerCase());
      }
      if (language) {
        const norm = normalizeLang(language);
        filtered = filtered.filter(w => w.language.toLowerCase() === norm.toLowerCase());
      }
      return {
        count: Math.min(filtered.length, limit),
        words: filtered.slice(0, limit)
      };
    }
  }

  /**
   * Fetch unique, alphabetically sorted categories
   */
  async function getCategories() {
    try {
      return await requestApi('/api/categories');
    } catch (err) {
      return {
        categories: OFFLINE_CATEGORIES,
        count: OFFLINE_CATEGORIES.length
      };
    }
  }

  /**
   * Search words across local, Hindi, English, category, and language fields
   */
  async function searchWords(query, category = "", language = "", limit = 10) {
    if (!query || !query.trim()) {
      return { count: 0, words: [], query: "" };
    }
    try {
      const params = new URLSearchParams();
      params.append("q", query.trim());
      if (category && category !== "All") params.append("category", category);
      if (language) params.append("language", language);
      if (limit) params.append("limit", limit);
      return await requestApi(`/api/words/search?${params.toString()}`);
    } catch (err) {
      const q = cleanSearchTerm(query);
      let filtered = OFFLINE_WORDS.filter(w => {
        const matchQ = cleanSearchTerm(w.english_word).includes(q) ||
                       cleanSearchTerm(w.hindi_word).includes(q) ||
                       cleanSearchTerm(w.local_word).includes(q);
        const matchCat = (!category || category === "All") || (w.category.toLowerCase() === category.toLowerCase());
        const matchLang = (!language) || (w.language.toLowerCase() === normalizeLang(language).toLowerCase());
        return matchQ && matchCat && matchLang;
      });
      return {
        count: Math.min(filtered.length, limit),
        query: query,
        words: filtered.slice(0, limit)
      };
    }
  }

  /**
   * Fetch random words for flashcards, learning games, and quizzes
   */
  async function getRandomWords(category = "", language = "", count = 5) {
    try {
      const params = new URLSearchParams();
      if (category && category !== "All") params.append("category", category);
      if (language) params.append("language", language);
      if (count) params.append("count", count);
      const qs = params.toString() ? `?${params.toString()}` : "";
      return await requestApi(`/api/words/random${qs}`);
    } catch (err) {
      let pool = OFFLINE_WORDS;
      if (category && category !== "All") {
        pool = pool.filter(w => w.category.toLowerCase() === category.toLowerCase());
      }
      if (language) {
        pool = pool.filter(w => w.language.toLowerCase() === normalizeLang(language).toLowerCase());
      }
      const shuffled = [...pool].sort(() => 0.5 - Math.random());
      return {
        count: Math.min(shuffled.length, count),
        words: shuffled.slice(0, count)
      };
    }
  }

  /**
   * Exact dictionary translation lookup
   * Tries backend API first; falls back seamlessly to offline dataset
   */
  async function translateWord(text, fromLanguage = "english", toLanguage = "local", targetLanguage = "") {
    try {
      return await requestApi('/api/translate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          text: text.trim(),
          fromLanguage: fromLanguage,
          toLanguage: toLanguage,
          targetLanguage: targetLanguage
        })
      });
    } catch (err) {
      console.info("[WordAPI] Live backend unavailable, using offline CSV dataset:", err.message);
      return offlineTranslate(text, fromLanguage, toLanguage, targetLanguage);
    }
  }

